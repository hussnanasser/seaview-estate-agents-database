-- REPORT 6: Viewings for Property PR01 with Buyer and Employee names --

SELECT
    vw.dateAndTime,
    prop.propertyAddress,
    buy.fullName AS Buyer,
    emp.fullName AS Staff
FROM VIEWING vw
JOIN PROPERTY prop ON vw.propertyID = prop.propertyID
JOIN BUYER buy ON vw.buyerID = buy.buyerID
JOIN EMPLOYEE emp ON vw.employeeID = emp.employeeID
WHERE vw.propertyID = 'PR01';

-- REPORT 10: List properties and their room counts --
-- Using left join so properties with no rooms still show up with 0 --
SELECT
    p.propertyID,
    p.propertyAddress,
    COUNT(rm.roomID) AS RoomCount
FROM PROPERTY p
LEFT JOIN ROOM rm ON p.propertyID = rm.propertyID
GROUP BY p.propertyID, p.propertyAddress;

