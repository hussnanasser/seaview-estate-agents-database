DROP TABLE BRANCH CASCADE CONSTRAINTS;


-- Create table scripts for Seaview Estate Agents --
-- Parent tables (BRANCH, OWNER, BUYER) are created before the tables that reference them --

CREATE TABLE BRANCH (
    branchID CHAR(5),
    address VARCHAR2(100) NOT NULL,
    phoneNo VARCHAR2(15),
    faxNo VARCHAR2(15),
    emailAddress VARCHAR2(50),
    CONSTRAINT pk_branch PRIMARY KEY (branchID)
);

CREATE TABLE OWNER (
    ownerID CHAR(5),
    fullName VARCHAR2(50) NOT NULL,
    contactNo VARCHAR2(15),
    emailAddress VARCHAR2(50),
    CONSTRAINT pk_owner PRIMARY KEY (ownerID)
);

CREATE TABLE EMPLOYEE (
    employeeID CHAR(5),
    fullName VARCHAR2(50) NOT NULL,
    address VARCHAR2(100),
    dob DATE,
    contactNo VARCHAR2(15),
    nationalInsuranceNo CHAR(9) UNIQUE,
    salary NUMBER(10, 2),
    startDate DATE NOT NULL,
    branchID CHAR(5),
    CONSTRAINT pk_employee PRIMARY KEY (employeeID),
    CONSTRAINT fk_emp_branch FOREIGN KEY (branchID) REFERENCES BRANCH(branchID)
);

CREATE TABLE BUYER (
    buyerID CHAR(5),
    fullName VARCHAR2(50) NOT NULL,
    contactNo VARCHAR2(15),
    emailAddress VARCHAR2(50),
    desiredNoOfRooms NUMBER(2),
    maxPrice NUMBER(12, 2),
    CONSTRAINT pk_buyer PRIMARY KEY (buyerID)
);

CREATE TABLE PROPERTY (
    propertyID CHAR(5),
    propertyAddress VARCHAR2(100) NOT NULL,
    propertyType VARCHAR2(20),
    askingPrice NUMBER(12, 2) NOT NULL,
    propertyStatus VARCHAR2(20), -- e.g., 'Available', 'Sold', 'Pending'
    ownerID CHAR(5) NOT NULL,
    branchID CHAR(5) NOT NULL,
    CONSTRAINT pk_property PRIMARY KEY (propertyID),
    CONSTRAINT fk_prop_owner FOREIGN KEY (ownerID) REFERENCES OWNER(ownerID),
    CONSTRAINT fk_prop_branch FOREIGN KEY (branchID) REFERENCES BRANCH(branchID)
);

CREATE TABLE ROOM (
    roomID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    length NUMBER(5,2),
    width NUMBER(5,2),
    noOfWindows NUMBER(2) DEFAULT 0,
    propertyID CHAR(5),
    CONSTRAINT pk_room PRIMARY KEY (roomID),
    CONSTRAINT fk_room_prop FOREIGN KEY (propertyID) REFERENCES PROPERTY(propertyID)
);

CREATE TABLE VIEWING (
    viewingID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    dateAndTime TIMESTAMP NOT NULL,
    propertyID CHAR(5) NOT NULL,
    buyerID CHAR(5) NOT NULL,
    employeeID CHAR(5) NOT NULL,
    CONSTRAINT pk_viewing PRIMARY KEY (viewingID),
    CONSTRAINT fk_view_prop FOREIGN KEY (propertyID) REFERENCES PROPERTY(propertyID),
    CONSTRAINT fk_view_buyer FOREIGN KEY (buyerID) REFERENCES BUYER(buyerID),
    CONSTRAINT fk_view_emp FOREIGN KEY (employeeID) REFERENCES EMPLOYEE(employeeID)
);


